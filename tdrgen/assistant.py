from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from typing import Any

from .config import Settings
from .engine import TDR_KEY_LINE, parse_entries, recommend
from .policy import build_system_prompt
from .tools import Toolbox

MAX_TOOL_ROUNDS = 8
SYSTEM_PROMPT = build_system_prompt()
TDR_WORDS = ("tdr", "script", "generate", "create", "build", "file")
LEAD_IN = re.compile(
    r"^\W*(?:please\s+)?(?:generate|create|build|make|write)\b.*?\b(?:for|from|with|of)\b[:\s]*",
    re.IGNORECASE,
)
COMMA_BREAK = re.compile(r",\s+(?=Z[A-Za-z0-9]{2,})")
MESSAGE_ID = re.compile(r"\b[A-Za-z]{3,5}\d{3,4}[A-Za-z]\b")
MESSAGE_PARTS = re.compile(r"([A-Z]+)(\d+)([A-Z])")
CLASSIFICATION = re.compile(r"\*\*Operational Classification\*\*:\s*(.+)")
CONFIRMED_STATUSES = ("user-provided", "catalog-exact", "ibm-example")
SEVERITY = {"I": "informational", "W": "warning", "E": "error"}
OFFLINE_FOOTNOTE = (
    "\n\n_Claude is not configured (ANTHROPIC_API_KEY), so this answer was assembled from local sources "
    "and IBM documentation rather than generated by an AI._"
)


@dataclass
class ToolCall:
    name: str
    arguments: dict[str, Any]
    result: Any
    is_error: bool = False


@dataclass
class Reply:
    text: str
    tool_calls: list[ToolCall] = field(default_factory=list)
    model: str | None = None

    @property
    def offline(self) -> bool:
        return self.model is None


class AssistantError(RuntimeError):
    pass


def _api_errors() -> tuple[type[BaseException], ...]:
    try:
        import anthropic
    except ImportError:
        return ()
    return (anthropic.APIError,)


class Assistant:
    def __init__(self, settings: Settings, toolbox: Toolbox | None = None, client: Any = None):
        self.settings = settings
        self.toolbox = toolbox or Toolbox(settings)
        self._client = client

    @property
    def online(self) -> bool:
        return self._client is not None or bool(self.settings.api_key)

    def ask(self, question: str, history: list[dict[str, str]] | None = None) -> Reply:
        question = question.strip()
        if not question:
            raise AssistantError("Question is empty.")
        if not self.online:
            return self._offline_reply(question)
        return self._converse(question, history or [])

    def _client_or_raise(self) -> Any:
        if self._client is None:
            try:
                import anthropic
            except ImportError as exc:
                raise AssistantError("The 'anthropic' package is not installed. Run: pip install anthropic") from exc
            self._client = anthropic.Anthropic(api_key=self.settings.api_key)
        return self._client

    def _converse(self, question: str, history: list[dict[str, str]]) -> Reply:
        client = self._client_or_raise()
        messages: list[dict[str, Any]] = [*history, {"role": "user", "content": question}]
        calls: list[ToolCall] = []

        for _ in range(MAX_TOOL_ROUNDS):
            try:
                response = client.messages.create(
                    model=self.settings.model,
                    max_tokens=self.settings.max_tokens,
                    system=SYSTEM_PROMPT,
                    tools=self.toolbox.definitions,
                    messages=messages,
                )
            except _api_errors() as exc:
                raise AssistantError(f"Claude API request failed: {exc}") from exc

            if response.stop_reason != "tool_use":
                text = "\n\n".join(b.text for b in response.content if b.type == "text").strip()
                if response.stop_reason == "max_tokens":
                    text += "\n\n_(Answer truncated: max_tokens reached.)_"
                return Reply(text or "(No answer returned.)", calls, self.settings.model)

            messages.append({"role": "assistant", "content": response.content})
            results = []
            for block in response.content:
                if block.type != "tool_use":
                    continue
                result, is_error = self.toolbox.run(block.name, block.input)
                calls.append(ToolCall(block.name, block.input, result, is_error))
                results.append({
                    "type": "tool_result",
                    "tool_use_id": block.id,
                    "content": json.dumps(result, default=str),
                    "is_error": is_error,
                })
            messages.append({"role": "user", "content": results})

        raise AssistantError(f"Claude did not finish within {MAX_TOOL_ROUNDS} tool rounds.")

    def _run(self, calls: list[ToolCall], name: str, arguments: dict[str, Any]) -> tuple[Any, bool]:
        result, is_error = self.toolbox.run(name, arguments)
        calls.append(ToolCall(name, arguments, result, is_error))
        return result, is_error

    def _offline_reply(self, question: str) -> Reply:
        calls: list[ToolCall] = []
        entries, global_unexpected = extract_entries(question)
        wants_tdr = any(word in question.lower() for word in TDR_WORDS) or len(entries) > 1

        text = self._offline_tdr(entries, global_unexpected, calls) if entries and wants_tdr else None
        if text is None:
            message_id = _message_id_in(question)
            command = None if message_id else self._known_command(question)
            if message_id:
                text = self._offline_message(message_id, calls)
            elif command:
                text = self._offline_command(command, calls)
            else:
                text = self._offline_general(question, calls)
        return Reply(text + OFFLINE_FOOTNOTE, calls, None)

    def _known_command(self, question: str) -> str | None:
        command = _command_in(question)
        if not command:
            return None
        if self.toolbox.ibm.find(command) is not None:
            return command
        if recommend(command, self.toolbox.catalog, limit=1):
            return command
        return None

    def _offline_tdr(self, entries: list[dict[str, Any]], global_unexpected: list[str], calls: list[ToolCall]) -> str | None:
        arguments: dict[str, Any] = {"commands": entries, "default_timeout": 120}
        if global_unexpected:
            arguments["global_unexpected"] = global_unexpected
        result, is_error = self._run(calls, "generate_tdr_from_entries", arguments)
        if is_error or not result.get("valid"):
            return None
        details = result.get("step_details", [])
        lines = [f"### Generated .TDR Script ({len(details)} command(s))", "", f"```tdr\n{result['tdr']}```", ""]
        lines.append("**Where each expected response came from**")
        for item in details:
            expected = ", ".join(f"`{value}`" for value in item["expected"])
            lines.append(f"- `{item['command']}` -> {expected} - {item['source']} ({item['status']})")
            if item["status"] not in CONFIRMED_STATUSES:
                lines.append(f"  - Review needed: {item['note']}")
            if item.get("is_state_change"):
                lines.append("  - State-changing command: operator approval and an approved change window are required.")
        review = sum(1 for item in details if item["status"] not in CONFIRMED_STATUSES)
        if review:
            lines.append(f"\n{review} step(s) need confirmation before the script is used. They are marked REVIEW in the file.")
        else:
            lines.append("\nEvery expected response is confirmed by the response catalog, IBM documentation or your input.")
        return "\n".join(lines)

    def _offline_command(self, command: str, calls: list[ToolCall]) -> str:
        lookup, _ = self._run(calls, "lookup_command", {"command": command, "limit": 6})
        page = lookup.get("ibm_documentation")
        if page is None:
            page, _ = self._run(calls, "lookup_ibm_documentation", {"command": command})
        entry = self.toolbox.ibm.find(command)

        classification = ""
        for hit in lookup.get("official_documentation", []):
            if entry and hit["heading"].upper().startswith(entry.command.upper()):
                match = CLASSIFICATION.search(hit["text"])
                if match:
                    classification = match.group(1).strip()
                    break

        asked = " ".join(command.upper().split())
        lines = [f"### {asked}"]
        found = page.get("found") if page else False
        if entry and entry.command.upper() != asked:
            lines.append(f"\nIBM documents this under the entry `{entry.command}`.")
        summary = (page.get("summary") if found else "") or (entry.description if entry else "")
        if summary:
            lines.append(f"\n**What it does:** {summary}")
        if classification:
            lines.append(f"\n**Classification:** {classification}")
        if "STATE-CHANGE" in classification.upper():
            lines.append("\n> Caution: this command changes system state. Operator approval and an approved change window are required.")

        responses: list[str] = []
        for row in lookup.get("reviewed_feedback", []):
            who = row["reviewer"] or "no reviewer"
            responses.append(f"- `{row['command']}` -> `{row['expected_response']}` - Reviewed feedback ({row['result']}, {who})")
        observed = lookup.get("historical_observations", [])
        for rec in [r for r in observed if r["match_type"] == "exact"]:
            responses.append(f"- `{rec['command']}` -> `{rec['response']}` - Response catalog (observed {rec['count']}x)")
        if found:
            for example in page.get("examples", [])[:4]:
                ids = ", ".join(f"`{value}`" for value in example["message_ids"]) or "no message ID shown"
                responses.append(f"- `{example['input']}` -> {ids} - IBM z/TPF documentation example")
        related = [r for r in observed if r["match_type"] != "exact"][:3]
        for rec in related:
            responses.append(f"- `{rec['command']}` -> `{rec['response']}` - Response catalog, related command (candidate only)")
        if responses:
            lines.append("\n**Responses to expect**\n\n" + "\n".join(responses))

        if found:
            sections = page.get("sections", {})
            restrictions = sections.get("Requirements and restrictions", "")
            if restrictions and restrictions.strip().rstrip(".").lower() != "none":
                lines.append(f"\n**Requirements and restrictions:** {_trim(restrictions, 600)}")
            fmt = sections.get("Format", "")
            if fmt:
                lines.append(f"\n**Format and parameters**\n\n```\n{_trim(fmt, 900)}\n```")
        elif page and page.get("reason"):
            lines.append(f"\n_IBM documentation was not consulted: {page['reason']}_")

        local_notes = [
            hit["text"] for hit in lookup.get("official_documentation", [])
            if hit["source"] not in ("ztpf_commands_catalog.md", "response_catalog.csv")
        ]
        if local_notes:
            lines.append("\n**Local runbook notes**\n\n" + "\n\n".join(f"- {_trim(note, 400)}" for note in local_notes[:2]))

        sources: list[str] = []
        for doc in lookup.get("official_documentation", []):
            if doc["source"] not in sources:
                sources.append(doc["source"])
        if lookup.get("reviewed_feedback") and "Reviewed feedback" not in sources:
            sources.append("Reviewed feedback")
        if observed and "Response catalog" not in sources:
            sources.append("Response catalog")
        if found:
            sources.append(f"IBM z/TPF documentation: {page['url']}")
        elif entry:
            sources.append(f"IBM command index: {entry.url}")
        if sources:
            lines.append("\n**Sources:** " + "; ".join(sources))
        if not summary and not responses:
            lines.append("\nNo local or IBM information was found for this command.")
        return "\n".join(lines)

    def _offline_message(self, message_id: str, calls: list[ToolCall]) -> str:
        search, _ = self._run(calls, "search_knowledge", {"query": message_id, "limit": 8})
        needle = message_id.upper()
        mentions: list[str] = []
        for hit in search.get("results", []):
            if hit["source"] == "response_catalog.csv":
                continue
            for line in hit["text"].splitlines():
                if needle in line.upper() and line.strip() not in mentions:
                    mentions.append(line.strip())

        producers: list[str] = []
        for row in self.toolbox.catalog:
            if needle in row.get("observed_expected_response", "").upper() and row["command"] not in producers:
                producers.append(row["command"])

        lines = [f"### {needle}"]
        parts = MESSAGE_PARTS.match(needle)
        prefix, severity = (parts.group(1), parts.group(3)) if parts else ("", "")
        meaning = self._prefix_meaning(prefix) if prefix else ""
        if meaning:
            lines.append(f"\n**Component prefix `{prefix}`:** {meaning}")
        if severity in SEVERITY:
            lines.append(f"\n**Severity `{severity}`:** {SEVERITY[severity]}")
        if mentions:
            lines.append("\n**Where it is documented**\n\n" + "\n".join(f"- {_trim(line.lstrip('-* '), 300)}" for line in mentions[:5]))
        if producers:
            shown = "\n".join(f"- `{command}`" for command in producers[:8])
            extra = f"\n- and {len(producers) - 8} more" if len(producers) > 8 else ""
            lines.append(f"\n**Commands observed returning it (Response catalog)**\n\n{shown}{extra}")
        sources = [name for name, present in (("Knowledge base", mentions or meaning), ("Response catalog", producers)) if present]
        if sources:
            lines.append("\n**Sources:** " + "; ".join(sources))
        else:
            lines.append(
                "\nThis message is not in the local knowledge base or response catalog, and the IBM command index "
                "does not cover message text. Add the message reference to the knowledge folder or configure Claude."
            )
        return "\n".join(lines)

    def _prefix_meaning(self, prefix: str) -> str:
        pattern = re.compile(rf"^\s*-\s*`{re.escape(prefix)}`:\s*(.+)$", re.IGNORECASE)
        for passage in self.toolbox.knowledge.passages:
            for line in passage.text.splitlines():
                match = pattern.match(line)
                if match:
                    return match.group(1).strip()
        return ""

    def _offline_general(self, question: str, calls: list[ToolCall]) -> str:
        search, _ = self._run(calls, "search_knowledge", {"query": question, "limit": 4})
        hits = search.get("results", [])
        if not hits:
            return (
                "I could not find anything about that in the local knowledge base. Try a command such as "
                "`ZSTAT DACS`, a message ID such as `CORE0397I`, or paste a list of commands to build a TDR."
            )
        lines = ["### Closest matches in the knowledge base"]
        for hit in hits:
            source = "Response catalog" if hit["source"] == "response_catalog.csv" else hit["source"]
            heading = f" - {hit['section']}" if hit["section"] else ""
            lines.append(f"\n**{source}{heading}**\n\n{_trim(hit['text'], 700)}")
        return "\n".join(lines)


def _trim(text: str, limit: int) -> str:
    text = text.strip()
    return text if len(text) <= limit else text[:limit].rstrip() + " ..."


def _message_id_in(question: str) -> str | None:
    match = MESSAGE_ID.search(question)
    return match.group(0).upper() if match else None


def extract_entries(text: str) -> tuple[list[dict[str, Any]], list[str]]:
    if any(TDR_KEY_LINE.match(line) for line in text.splitlines()):
        entries, global_unexpected = parse_entries(text)
        return _unique_entries(entries), global_unexpected

    commands: list[str] = []
    for raw in text.splitlines():
        line = LEAD_IN.sub("", raw.strip().lstrip("-*0123456789.) \t")).strip().rstrip(";")
        if not line:
            continue
        for part in COMMA_BREAK.split(line):
            part = part.strip().rstrip(",;")
            if not part:
                continue
            first = part.split()[0].upper()
            if first.startswith("Z") and len(first) >= 3:
                commands.append(part)
    if not commands:
        return [], []
    entries, _ = parse_entries("\n".join(commands))
    return _unique_entries(entries), []


def _unique_entries(entries: list[dict[str, Any]]) -> list[dict[str, Any]]:
    seen: set[tuple[str, tuple[str, ...]]] = set()
    unique: list[dict[str, Any]] = []
    for entry in entries:
        key = (entry["command"], tuple(entry.get("expected") or ()))
        if key not in seen:
            seen.add(key)
            unique.append(entry)
    return unique


def _command_in(question: str) -> str | None:
    text = question.strip().rstrip("?.!")
    if re.fullmatch(r"[A-Za-z0-9][\w/\-.,= ]{0,60}", text) and len(text.split()) <= 6 and text.upper().startswith("Z"):
        return text
    tokens = question.rstrip("?.!").split()
    for index, token in enumerate(tokens):
        word = token.strip(",;:()")
        if re.fullmatch(r"Z[A-Za-z]{2,7}", word):
            parts = [word.upper()]
            for follower in tokens[index + 1:index + 4]:
                bare = follower.strip(",;:()")
                if bare and (bare.isupper() or any(ch.isdigit() for ch in bare)):
                    parts.append(bare)
                else:
                    break
            return " ".join(parts)
    return None
